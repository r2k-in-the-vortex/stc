/// Returns whether `code` is a documented diagnostic code.
pub(crate) fn is_known(code: &str) -> bool {
    KNOWN_CODES.binary_search(&code).is_ok()
}

#[cfg(test)]
mod tests {
    use super::KNOWN_CODES;

    #[test]
    fn codes_are_sorted_and_unique() {
        for pair in KNOWN_CODES.windows(2) {
            assert!(pair[0] < pair[1], "{} is not before {}", pair[0], pair[1]);
        }
    }
}
